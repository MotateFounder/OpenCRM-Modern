// Preload: exposes a small, whitelisted API to the sandboxed renderer as window.crm
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch, ...args) => ipcRenderer.invoke(ch, ...args).then((r) => {
  if (r && typeof r === 'object' && 'error' in r && Object.keys(r).length === 1) throw new Error(r.error);
  return r;
});
const on = (ch) => (cb) => {
  const fn = (_e, payload) => cb(payload);
  ipcRenderer.on(ch, fn);
  return () => ipcRenderer.removeListener(ch, fn);
};

contextBridge.exposeInMainWorld('crm', {
  state: () => call('state:get'),
  db: {
    open: (opts) => call('db:open', opts),
    create: (opts) => call('db:create', opts),
    save: (data) => call('db:save', data),
    moveTo: () => call('db:moveTo'),
    close: () => call('db:close'),
    recent: () => call('db:recent'),
    forget: (p) => call('db:forget', p),
    reveal: (p) => call('db:reveal', p),
    backups: () => call('db:backups'),
    readBackup: (file) => call('db:readBackup', file),
    exportFile: (opts) => call('db:exportFile', opts),
    importParse: (o) => call('db:importParse', o),
    onExternalChange: on('db:external-change'),
  },
  files: {
    add: (opts) => call('files:add', opts),
    open: (rel) => call('files:open', rel),
    reveal: (rel) => call('files:reveal', rel),
    trash: (rel) => call('files:trash', rel),
    setPicture: (opts) => call('files:setPicture', opts),
    extract: (opts) => call('files:extract', opts),
    pathFor: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  },
  aiRuntime: {
    state: () => call('ai-runtime:state'),
    download: (id) => call('ai-runtime:download', { id }),
    cancel: (id) => call('ai-runtime:cancel', { id }),
    use: (o) => call('ai-runtime:use', o),
    disable: () => call('ai-runtime:disable'),
    setMode: (startMode) => call('ai-runtime:setMode', { startMode }),
    start: () => call('ai-runtime:start'),
    stop: () => call('ai-runtime:stop'),
    remove: (id) => call('ai-runtime:remove', { id }),
    openFolder: () => call('ai-runtime:openFolder'),
    onState: on('ai-runtime:state'),
    onProgress: on('ai-runtime:progress'),
  },
  ai: {
    models: (o) => call('ai:models', o),
    test: (o) => call('ai:test', o),
    chat: (o) => call('ai:chat', o),
    abort: (id) => call('ai:abort', id),
    setKey: (k) => call('ai:setKey', k),
    onChunk: on('ai:chunk'),
    semanticSearch: (o) => call('semantic:search', o),
    onSemanticProgress: on('semantic:progress'),
  },
  config: { update: (patch) => call('config:update', patch) },
  mail: {
    presets: () => call('mail:presets'),
    guess: (email) => call('mail:guess', email),
    accounts: () => call('mail:accounts'),
    saveAccount: (o) => call('mail:saveAccount', o),
    removeAccount: (id) => call('mail:removeAccount', id),
    testAccount: (o) => call('mail:testAccount', o),
    status: () => call('mail:status'),
    syncNow: (id) => call('mail:syncNow', id),
    list: (o) => call('mail:list', o),
    threads: (o) => call('mail:threads', o),
    get: (key) => call('mail:get', key),
    markRead: (o) => call('mail:markRead', o),
    stats: () => call('mail:stats'),
    attachment: (o) => call('mail:attachment', o),
    pickFiles: () => call('mail:pickFiles'),
    send: (o) => call('mail:send', o),
    undo: (id) => call('mail:undo', id),
    outbox: () => call('mail:outbox'),
    retry: (id) => call('mail:retry', id),
    discard: (id) => call('mail:discard', id),
    bulk: (o) => call('mail:bulk', o),
    bulkControl: (o) => call('mail:bulkControl', o),
    drafts: (o) => call('mail:drafts', o),
    inlineCss: (html) => call('mail:inlineCss', html),
    tracker: (o) => call('mail:tracker', o),
    oauth: (o) => call('mail:oauth', o),
    searchText: () => call('mail:searchText'),
    onEvent: on('mail:event'),
  },
  agent: {
    state: () => call('agents:state'),
    createClient: (o) => call('agents:createClient', o),
    updateClient: (o) => call('agents:updateClient', o),
    revoke: (id) => call('agents:revoke', id),
    global: (o) => call('agents:global', o),
    command: () => call('agents:command'),
    approvals: (o) => call('agents:approvals', o),
    resolve: (o) => call('agents:resolve', o),
    activity: (o) => call('agents:activity', o),
    changeset: (id) => call('agents:changeset', id),
    undo: (o) => call('agents:undo', o),
    reply: (reqId, result) => ipcRenderer.invoke('agent:reply', { reqId, result }),
    onCall: on('agent:call'),
    onUndo: on('agent:undo'),
    onChanged: on('agents:changed'),
  },
  app: {
    notify: (o) => call('app:notify', o),
    print: () => call('app:print'),
    pdf: (o) => call('app:pdf', o),
    openExternal: (url) => call('app:openExternal', url),
    clipboard: (text) => call('app:clipboard', text),
    flushed: (o) => call('app:flushed', o),
    quit: () => call('app:quit'),
    userTemplates: (o) => call('app:userTemplates', o),
    importTemplateFile: () => call('app:importTemplateFile'),
    onFlushRequest: on('app:flush-request'),
    onOpenRecord: on('app:open-record'),
    onWarning: on('app:warning'),
    onQuickAddNote: on('quickadd:note'),
  },
  quick: {
    records: () => call('quick:records'),
    add: (p) => call('quick:add', p),
    close: () => call('quick:close'),
    onShown: on('quick:shown'),
  },
});
